// Package render builds the Caddyfile served by the proxy stack.
package render

import (
	"fmt"
	"strings"

	"github.com/harrisonclewis/ship/internal/config"
)

const header = `# Generated by ship from ship.yaml. Do not edit; run ` + "`ship proxy update`" + `.

(common) {
	encode zstd gzip
	header Strict-Transport-Security "max-age=31536000"
}
`

// Caddyfile renders one server's apps' domains and redirects deterministically.
func Caddyfile(s *config.Server) string {
	var b strings.Builder
	b.WriteString(header)
	for _, name := range s.AppNames() {
		app := s.Apps[name]
		fmt.Fprintf(&b, "\n%s {\n\timport common\n", strings.Join(app.Domains, ", "))
		writeMaintenance(&b, name)
		fmt.Fprintf(&b, "\thandle {\n\t\treverse_proxy %s\n\t}\n}\n", app.Upstream)
	}
	for _, name := range s.AppNames() {
		app := s.Apps[name]
		for _, host := range app.Redirects {
			fmt.Fprintf(&b, "\n%s {\n", host)
			writeMaintenance(&b, name)
			fmt.Fprintf(&b, "\thandle {\n\t\tredir https://%s{uri} permanent\n\t}\n}\n",
				app.Domains[0])
		}
	}
	return b.String()
}

// writeMaintenance serves a 503 for an app while its flag file exists. The
// proxy mounts /opt/proxy/maintenance read-only at /etc/caddy/maintenance, so
// toggling the file needs no reload.
func writeMaintenance(b *strings.Builder, app string) {
	fmt.Fprintf(b, "\t@maintenance file {\n\t\troot /etc/caddy/maintenance\n\t\ttry_files %s\n\t}\n", app)
	b.WriteString("\thandle @maintenance {\n")
	b.WriteString("\t\theader Retry-After 120\n")
	b.WriteString("\t\trespond \"Maintenance in progress. Try again soon.\" 503\n")
	b.WriteString("\t}\n")
}
