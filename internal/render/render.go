// Package render builds the Caddyfile served by the proxy stack.
package render

import (
	"fmt"
	"sort"
	"strings"

	"github.com/harrisonclewis/ship/internal/config"
)

const header = `# Generated by ship from the server's app records. Do not edit; run ` + "`ship proxy sync`" + `.

(common) {
	encode zstd gzip
	header Strict-Transport-Security "max-age=31536000"
}
`

// App is one app's live routing inputs. Domains and Redirects come from the
// desired record; Upstream comes from the running record. Deployed is false for
// an app that has never been deployed, which is skipped.
type App struct {
	Name      string
	Domains   []string
	Redirects []string
	Upstream  string
	Deployed  bool
}

// CaddyfileFor renders a server's apps deterministically from server data.
func CaddyfileFor(apps []App) string {
	apps = append([]App(nil), apps...)
	sort.Slice(apps, func(i, j int) bool { return apps[i].Name < apps[j].Name })

	var b strings.Builder
	b.WriteString(header)
	for _, app := range apps {
		if !app.Deployed || len(app.Domains) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n%s {\n\timport common\n", strings.Join(app.Domains, ", "))
		writeMaintenance(&b, app.Name)
		fmt.Fprintf(&b, "\thandle {\n\t\treverse_proxy %s\n\t}\n}\n", app.Upstream)
	}
	for _, app := range apps {
		if !app.Deployed || len(app.Domains) == 0 {
			continue
		}
		for _, host := range app.Redirects {
			fmt.Fprintf(&b, "\n%s {\n", host)
			writeMaintenance(&b, app.Name)
			fmt.Fprintf(&b, "\thandle {\n\t\tredir https://%s{uri} permanent\n\t}\n}\n",
				app.Domains[0])
		}
	}
	return b.String()
}

// Caddyfile renders one server's records in the legacy shape. Callers with
// server data should use CaddyfileFor.
func Caddyfile(s *config.Server) string {
	apps := make([]App, 0, len(s.Apps))
	for _, name := range s.AppNames() {
		app := s.Apps[name]
		apps = append(apps, App{
			Name:      name,
			Domains:   app.Domains,
			Redirects: app.Redirects,
			Upstream:  app.Upstream,
			Deployed:  true,
		})
	}
	return CaddyfileFor(apps)
}

// writeMaintenance serves a 503 for an app while its flag file exists. The
// proxy mounts /opt/proxy/maintenance read-only at /etc/caddy/maintenance, so
// toggling the file needs no reload.
func writeMaintenance(b *strings.Builder, app string) {
	fmt.Fprintf(b, "\t@maintenance file {\n\t\troot /etc/caddy/maintenance\n\t\ttry_files %s\n\t}\n", app)
	b.WriteString("\thandle @maintenance {\n")
	b.WriteString("\t\theader Retry-After 120\n")
	b.WriteString("\t\trespond \"Maintenance in progress. Try again soon.\" 503\n")
	b.WriteString("\t}\n")
}
