package ops

import (
	"archive/tar"
	"bytes"
	"errors"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
	"testing"

	"go.yaml.in/yaml/v3"
)

func TestAgentRegeneratesCombinedFileAndExportsOnlyRecords(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("the agent test harness needs bash")
	}
	for _, tool := range []string{"bash", "tar"} {
		if _, err := exec.LookPath(tool); err != nil {
			t.Skipf("%s is not installed", tool)
		}
	}
	// The agent targets Linux servers with bash 4+ (it uses associative
	// arrays); macOS still ships bash 3.2.
	if err := exec.Command("bash", "-c", "declare -A probe=()").Run(); err != nil {
		t.Skip("the agent needs bash 4 or newer")
	}
	// The agent's tar invocation uses GNU options; skip other tar variants.
	if err := exec.Command("sh", "-c", "tar --no-same-owner -cf /dev/null --files-from /dev/null").Run(); err != nil {
		t.Skip("tar does not support the agent's GNU options")
	}

	agent, err := filepath.Abs("../../ship-agent")
	if err != nil {
		t.Fatal(err)
	}
	work := t.TempDir()
	upload := filepath.Join(work, "files.tar")
	members := map[string]string{
		"compose.yaml":  "name: app\n",
		"Dockerfile":    "FROM scratch\n",
		"ship-app.yaml": "domains: [app.example.com]\nupstream: app:8080\nsource:\n  type: image\n",
		".ship-meta":    "version=1\napp=app\nsource=image\n",
		".ship-env":     "PUBLIC=one\n",
	}
	var blob bytes.Buffer
	tw := tar.NewWriter(&blob)
	for name, data := range members {
		if err := tw.WriteHeader(&tar.Header{Name: name, Mode: 0o644, Size: int64(len(data))}); err != nil {
			t.Fatal(err)
		}
		if _, err := tw.Write([]byte(data)); err != nil {
			t.Fatal(err)
		}
	}
	if err := tw.Close(); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(upload, blob.Bytes(), 0o644); err != nil {
		t.Fatal(err)
	}

	harness := filepath.Join(work, "harness.sh")
	script := `set -euo pipefail
source "$AGENT"
APPS="$WORK/apps"
PROXY="$WORK/proxy"
BACKUPS="$WORK/backups"
mkdir -p "$APPS" "$PROXY" "$BACKUPS"
app_files app < "$WORK/files.tar"
app_export > "$WORK/export.tar"
printf 'SECRET=1\n' > "$APPS/app/.env"
printf 'current=v1\nprevious=\n' > "$APPS/app/.ship-state"
app_export > "$WORK/export2.tar"
`
	if err := os.WriteFile(harness, []byte(script), 0o644); err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command("bash", harness)
	cmd.Env = append(os.Environ(), "AGENT="+agent, "WORK="+work)
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("agent harness: %v\n%s", err, out)
	}

	combined, err := os.ReadFile(filepath.Join(work, "apps", "ship.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"# Generated by ship",
		"apps:",
		"  app:",
		"    domains: [app.example.com]",
		"    upstream: app:8080",
	} {
		if !strings.Contains(string(combined), want) {
			t.Errorf("combined ship.yaml missing %q:\n%s", want, combined)
		}
	}
	var parsed map[string]any
	if err := yaml.Unmarshal(combined, &parsed); err != nil {
		t.Fatalf("combined ship.yaml is not valid YAML: %v\n%s", err, combined)
	}

	for _, name := range []string{"export.tar", "export2.tar"} {
		got, err := tarNames(filepath.Join(work, name))
		if err != nil {
			t.Fatal(err)
		}
		want := map[string]bool{
			"app/ship-app.yaml": true,
			"app/compose.yaml":  true,
			"app/Dockerfile":    true,
		}
		if len(got) != len(want) {
			t.Fatalf("%s members = %v", name, got)
		}
		for _, member := range got {
			if !want[member] {
				t.Errorf("%s exported unexpected member %q", name, member)
			}
		}
	}
}

func tarNames(path string) ([]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	tr := tar.NewReader(f)
	var names []string
	for {
		hdr, err := tr.Next()
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			return nil, err
		}
		names = append(names, hdr.Name)
	}
	return names, nil
}
